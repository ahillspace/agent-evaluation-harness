import type {
  RunPerformance,
  UsageReporting,
} from "../contracts/assessment-passes.js";
import { duration, Help, Metric } from "./ui.js";

const count = (value: number | null | undefined) =>
  value == null ? "Unknown" : value.toLocaleString();
const elapsed = (value: number | null | undefined) =>
  value == null ? "Unknown" : duration(value);
const compactCount = new Intl.NumberFormat("en-US", {
  notation: "compact",
  maximumFractionDigits: 2,
});

export function TokenUsageHelp() {
  return (
    <Help label="Token counts">
      Input is newly processed text, excluding reused input. Output is text
      generated by the model. Cache is previously processed input reused by the
      provider. Counts cover reported requests; pending and missing reports
      appear separately.
    </Help>
  );
}

export function UsageValue({
  value,
  reporting,
}: {
  value: number | null | undefined;
  reporting?: UsageReporting["inputTokens"];
}) {
  const incomplete =
    !!reporting && (reporting.missing > 0 || reporting.pending > 0);
  const label =
    value == null
      ? reporting?.missing
        ? "Not reported"
        : reporting?.pending
          ? "Pending"
          : "Unknown"
      : compactCount.format(value);
  return (
    <span className="usage-value">
      <span title={value == null ? undefined : value.toLocaleString("en-US")}>
        {label}
      </span>
      {incomplete && (
        <small>
          {[
            reporting.reported > 0 ? `${reporting.reported} reported` : "",
            reporting.missing > 0 ? `${reporting.missing} not reported` : "",
            reporting.pending > 0 ? `${reporting.pending} pending` : "",
          ]
            .filter(Boolean)
            .join(" · ")}
        </small>
      )}
    </span>
  );
}

export function RunPerformanceSummary({
  performance,
}: {
  performance?: RunPerformance;
}) {
  return (
    <section className="panel">
      <div className="panel-heading">
        <h2>Performance</h2>
        <Help
          label="Run performance"
          tooltip="Review execution time, reported usage, and usage coverage. Open for token and attribution details."
        >
          <p>
            Run duration adds active execution time and excludes idle gaps.
            Incomplete historical or interrupted timing appears as Unknown.
            Answer time covers completed attempts. Turns are agent steps; tool
            calls are requests to connected tools.
          </p>
          <p>
            Tokens measure text sent to and received from models. Totals include
            all reported requests; pending or unreported requests appear
            separately. Input excludes reused text, which appears under Cache.
            Output is generated text. Reused conversation context can make
            cumulative cache counts much larger than one question. Missing cache
            reports also leave uncached input unreported. Large counts use K for
            thousand and M for million; hover over a count for its exact value.
          </p>
          <p>
            Researcher usage counts decisions made after this run. Roles with no
            attributed turns or calls are omitted.
          </p>
        </Help>
      </div>
      <div className="panel-body">
        <div className="performance-metrics">
          <Metric
            label="Run duration"
            value={elapsed(performance?.durationMs)}
          />
          <Metric
            label="Average answer time"
            value={elapsed(performance?.answerLatencyMs.average)}
          />
          <Metric
            label="Slowest answer"
            value={elapsed(performance?.answerLatencyMs.maximum)}
          />
          <Metric
            label="Attempts"
            value={count(performance?.attempts)}
            detail={
              performance
                ? `${performance.retries} ${performance.retries === 1 ? "retry" : "retries"}`
                : "Retries unknown"
            }
          />
          <Metric
            label="Answers recorded"
            value={count(performance?.answered)}
          />
          <Metric
            label="Execution failures"
            value={count(performance?.failures)}
          />
        </div>
        <div className="table-scroll">
          <table className="performance-table">
            <thead>
              <tr>
                <th>Activity</th>
                <th>Input tokens</th>
                <th>Output tokens</th>
                <th>Cache tokens</th>
                <th>Turns / calls</th>
                <th>Tool calls</th>
              </tr>
            </thead>
            <tbody>
              <tr>
                <th>Target agent</th>
                <td>
                  <UsageValue
                    value={performance?.target.uncachedInputTokens}
                    reporting={
                      performance?.target.reporting?.uncachedInputTokens
                    }
                  />
                </td>
                <td>
                  <UsageValue
                    value={performance?.target.outputTokens}
                    reporting={performance?.target.reporting?.outputTokens}
                  />
                </td>
                <td>
                  <UsageValue
                    value={performance?.target.cachedInputTokens}
                    reporting={performance?.target.reporting?.cachedInputTokens}
                  />
                </td>
                <td>{count(performance?.target.turns)}</td>
                <td>{count(performance?.target.toolCalls)}</td>
              </tr>
              {performance?.researcher.turns !== 0 && (
                <tr>
                  <th>Researcher (this run)</th>
                  <td>
                    <UsageValue
                      value={performance?.researcher.uncachedInputTokens}
                      reporting={
                        performance?.researcher.reporting?.uncachedInputTokens
                      }
                    />
                  </td>
                  <td>
                    <UsageValue
                      value={performance?.researcher.outputTokens}
                      reporting={
                        performance?.researcher.reporting?.outputTokens
                      }
                    />
                  </td>
                  <td>
                    <UsageValue
                      value={performance?.researcher.cachedInputTokens}
                      reporting={
                        performance?.researcher.reporting?.cachedInputTokens
                      }
                    />
                  </td>
                  <td>{count(performance?.researcher.turns)}</td>
                  <td>Not recorded</td>
                </tr>
              )}
              {performance?.judge.calls !== 0 && (
                <tr>
                  <th>Judges</th>
                  <td>
                    <UsageValue
                      value={performance?.judge.uncachedInputTokens}
                      reporting={
                        performance?.judge.reporting?.uncachedInputTokens
                      }
                    />
                  </td>
                  <td>
                    <UsageValue
                      value={performance?.judge.outputTokens}
                      reporting={performance?.judge.reporting?.outputTokens}
                    />
                  </td>
                  <td>
                    <UsageValue
                      value={performance?.judge.cachedInputTokens}
                      reporting={
                        performance?.judge.reporting?.cachedInputTokens
                      }
                    />
                  </td>
                  <td>{count(performance?.judge.calls)}</td>
                  <td>Not applicable</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </section>
  );
}
