import type {
  RunPerformance,
  UsageReporting,
} from "../contracts/assessment-passes.js";
import { duration, Help, Metric } from "./ui.js";

const count = (value: number | null | undefined) =>
  value == null ? "Unknown" : value.toLocaleString();
const elapsed = (value: number | null | undefined) =>
  value == null ? "Unknown" : duration(value);
const compactCount = new Intl.NumberFormat("en-US", {
  notation: "compact",
  maximumFractionDigits: 2,
});

export function TokenUsageHelp() {
  return (
    <Help label="Token counts">
      Input is newly processed text, excluding reused input. Output is text
      generated by the model. Cache is previously processed input reused by the
      provider. Counts cover reported requests; pending and missing reports
      appear separately.
    </Help>
  );
}

export function UsageValue({
  value,
  reporting,
}: {
  value: number | null | undefined;
  reporting?: UsageReporting["inputTokens"];
}) {
  const incomplete =
    !!reporting && (reporting.missing > 0 || reporting.pending > 0);
  const label =
    value == null
      ? reporting?.missing
        ? "Not reported"
        : reporting?.pending
          ? "Pending"
          : "Unknown"
      : compactCount.format(value);
  return (
    <span className="usage-value">
      <span title={value == null ? undefined : value.toLocaleString("en-US")}>
        {label}
      </span>
      {incomplete && (
        <small>
          {[
            reporting.reported > 0 ? `${reporting.reported} reported` : "",
            reporting.missing > 0 ? `${reporting.missing} not reported` : "",
            reporting.pending > 0 ? `${reporting.pending} pending` : "",
          ]
            .filter(Boolean)
            .join(" · ")}
        </small>
      )}
    </span>
  );
}

export function RunPerformanceTotals({
  performance,
}: {
  performance?: RunPerformance;
}) {
  return (
    <div
      className="run-performance-totals"
      role="region"
      aria-label="Performance totals"
      tabIndex={0}
    >
      <Metric label="Run duration" value={elapsed(performance?.durationMs)} />
      <Metric
        label="Average answer"
        value={elapsed(performance?.answerLatencyMs.average)}
      />
      <div className="metric">
        <span>
          Input tokens <TokenUsageHelp />
        </span>
        <UsageValue
          value={performance?.target.uncachedInputTokens}
          reporting={performance?.target.reporting?.uncachedInputTokens}
        />
      </div>
      <div className="metric">
        <span>Output tokens</span>
        <UsageValue
          value={performance?.target.outputTokens}
          reporting={performance?.target.reporting?.outputTokens}
        />
      </div>
      <div className="metric">
        <span>Cache tokens</span>
        <UsageValue
          value={performance?.target.cachedInputTokens}
          reporting={performance?.target.reporting?.cachedInputTokens}
        />
      </div>
      <Metric label="Target turns" value={count(performance?.target.turns)} />
      <Metric label="Tool calls" value={count(performance?.target.toolCalls)} />
      <Metric
        label="Attempts"
        value={count(performance?.attempts)}
        detail={
          performance
            ? `${performance.retries} ${performance.retries === 1 ? "retry" : "retries"}`
            : undefined
        }
      />
    </div>
  );
}

